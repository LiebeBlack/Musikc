"""Export the generated QSS to ``resources/styles/studio.qss`` for auditing.

The runtime always builds the stylesheet from :mod:`src.ui.theme` (single source
of truth); this file is a readable artefact for designers and code review.

Usage:  python scripts/export_stylesheet.py
"""

from __future__ import annotations

import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

os.environ.setdefault("QT_QPA_PLATFORM", "offscreen")

from src.ui.theme import PALETTE, build_stylesheet


def main() -> int:
    target = ROOT / "resources" / "styles" / "studio.qss"
    target.parent.mkdir(parents=True, exist_ok=True)
    body = (
        "/* True HQ Audio — studio dark theme (generated by scripts/export_stylesheet.py)\n"
        " * Palette tokens are defined in src/ui/theme.py:Palette.\n"
        " */\n\n"
        + build_stylesheet(PALETTE)
    )
    target.write_text(body.strip() + "\n", encoding="utf-8")
    print(f"wrote {target} ({len(body)} chars)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
